def app_run(
    app: str,
    app_name: Optional[str],
    env: Optional[str],
    local_folder: Optional[Path],
    config_dir: Optional[Path],
    quiet: bool,
    local_packages: Tuple[Path, ...],
    parameters_path: Optional[Path],
    param_overrides: Tuple[str, ...],
    trace: bool,
    trace_level: Optional[str],
    platform: Optional[str],
    no_logs: bool,
    no_wait: bool,
    poll_interval: float,
    timeout: float,
    fail_on_error: bool,
    json_output: bool,
    dotenv_paths: Tuple[Path, ...],
    no_dotenv: bool,
    load_lake: bool = False,
) -> None:
    """Run an app locally or remotely on a managed platform.

    For standalone runs, APP is the app name and kindling looks up apps/<app>/ by
    convention. Use --local-folder to override for non-standard layouts.

    For remote runs (--platform), APP is the deployed app name. The app must already
    be deployed; use 'kindling app deploy APP --platform PLATFORM' first.

    \b
    --trace/--trace-level are documented sugar for
    --param print_trace=true/--param kindling.telemetry.tracing.level=<level>;
    an explicit --param for the same key still wins.
    """
    param_overrides = _prepend_trace_param_overrides(trace, trace_level, param_overrides)

    if platform == "standalone":
        if app_name:
            raise click.ClickException("--app-name is only valid for remote app runs.")
        if local_folder:
            resolved_app_ref = str(local_folder.expanduser().resolve())
        else:
            resolved_app_ref = str(_resolve_by_convention(app, "apps", "app"))
        resolved_dotenvs: Tuple[Path, ...]
        if no_dotenv:
            resolved_dotenvs = ()
        elif dotenv_paths:
            resolved_dotenvs = dotenv_paths
        else:
            resolved_dotenvs = (Path(".env"),)
        _run_standalone_app(
            resolved_app_ref,
            env,
            config_dir,
            platform,
            quiet,
            local_packages,
            parameters_path,
            param_overrides,
            no_logs,
            no_wait,
            json_output,
            fail_on_error=fail_on_error,
            dotenv_paths=resolved_dotenvs,
            load_lake=load_lake,
        )
        return

    if local_folder is not None:
        raise click.ClickException("--local-folder is only valid for standalone app runs.")
    if config_dir is not None:
        raise click.ClickException("--config is only valid for standalone app runs.")
    if quiet:
        raise click.ClickException("--quiet is only valid for standalone app runs.")
    if local_packages:
        raise click.ClickException("--local-package is only valid for standalone app runs.")
    if dotenv_paths or no_dotenv:
        raise click.ClickException("--dotenv/--no-dotenv is only valid for standalone app runs.")
    if load_lake:
        raise click.ClickException("--load-lake is only valid for standalone app runs.")

    _run_remote_app(
        app,
        app_name,
        env,
        parameters_path,
        param_overrides,
        platform,
        no_logs,
        no_wait,
        poll_interval,
        timeout,
        fail_on_error,
        json_output,
    )


