def _apply_trace_env_vars(trace: bool, trace_level: Optional[str]) -> None:
    """Set the env-var-gated tracing config Dynaconf reads once an app.py
    bootstraps (KINDLING_KINDLING__TELEMETRY__TRACING__PRINT/LEVEL), the
    same override Dynaconf applies to kindling.telemetry.tracing.print/level.

    Used by commands like `pipeline run` that have no --param plumbing of
    their own; `app run` instead implements --trace/--trace-level as sugar
    for --param print_trace=true/--param kindling.telemetry.tracing.level=
    since it already threads --param through to bootstrap. A flag left
    unset here leaves any ambient/.env-based tracing config untouched.
    """
    if trace:
        os.environ["KINDLING_KINDLING__TELEMETRY__TRACING__PRINT"] = "true"
    if trace_level:
        os.environ["KINDLING_KINDLING__TELEMETRY__TRACING__LEVEL"] = trace_level


def _prepend_trace_param_overrides(
    trace: bool, trace_level: Optional[str], param_overrides: Tuple[str, ...]
) -> Tuple[str, ...]:
    """Translate --trace/--trace-level into --param-shaped overrides and
    prepend them ahead of any explicit --param values.

    _resolve_runtime_parameters applies overrides in order via
    _set_nested_key, later entries winning -- prepending here means an
    explicit `--param print_trace=...`/`--param
    kindling.telemetry.tracing.level=...` passed alongside --trace/
    --trace-level still wins, consistent with how --param already overrides
    file-based and env-based parameters elsewhere.
    """
    synthetic: Tuple[str, ...] = ()
    if trace:
        synthetic += ("print_trace=true",)
    if trace_level:
        synthetic += (f"kindling.telemetry.tracing.level={trace_level}",)
    return (*synthetic, *param_overrides)


def _run_local_pipe(
    pipe_id: str,
    env: Optional[str],
    app_path: Optional[Path],
    config_dir: Optional[Path],
    quiet: bool,
    no_watermark: bool,
    trace: bool = False,
    trace_level: Optional[str] = None,
) -> None:
    """Execute a registered pipe locally."""
    try:
        from kindling.data_pipes import DataPipesExecution, DataPipesRegistry
        from kindling.injection import GlobalInjector
    except ImportError as exc:
        raise click.ClickException(
            "kindling package is required. Install with: pip install spark-kindling[standalone]"
        ) from exc

    if quiet:
        _configure_quiet_logging()
    _apply_trace_env_vars(trace, trace_level)

    resolved_env = env or os.getenv("KINDLING_ENV", "local")
    if env is not None and env != "local":
        click.echo(
            f"Note: --env {env} controls config loading only. "
            "To run remotely use: kindling app run <app> --platform <platform>"
        )
    if app_path is None and config_dir is None and not Path("settings.yaml").exists():
        raise click.ClickException(
            "Config file not found at settings.yaml.\n"
            "  Hint: Run `kindling config init` to generate a starter config, or use --config <path>."
        )
    resolved_app = _discover_app_py(app_path)
    _load_app_module(resolved_app, resolved_env, config_dir)

    registry = GlobalInjector.get(DataPipesRegistry)
    pipe = registry.get_pipe_definition(pipe_id)
    if pipe is None:
        available = ", ".join(registry.get_pipe_ids()) or "(none registered)"
        raise click.ClickException(
            f"Pipe '{pipe_id}' not found.\n"
            f"  Registered pipes: {available}\n"
            "  Hint: Check for typos, or run `kindling app validate` to see all registered pipes."
        )

    if no_watermark:
        click.echo("Note: --no-watermark is set; watermark tracking bypassed for this run.")
    click.echo(f"Running pipe: {pipe_id}")
    executer = GlobalInjector.get(DataPipesExecution)
    try:
        # [implementer] pass no_watermark through run_datapipes kwargs — ki-70y
        executer.run_datapipes([pipe_id], no_watermark=no_watermark)
    except Exception as exc:
        raise click.ClickException(f"Pipe '{pipe_id}' failed: {exc}") from exc
    click.echo(f"Pipe '{pipe_id}' completed successfully.")


def _build_entity_pipe_graph_checks(
    entity_registry: Any, pipe_registry: Any
) -> Tuple[List[Tuple[str, bool, str]], int, int]:
    """Build the entity/pipe registration + graph-integrity checks shared by
    `app validate` and `app check` (a superset of validate). Returns
    ``(checks, entity_count, pipe_count)``.
    """
    entity_ids = set(entity_registry.get_entity_ids())
    pipe_ids = list(pipe_registry.get_pipe_ids())

    checks: List[Tuple[str, bool, str]] = [
        ("entities_registered", len(entity_ids) > 0, f"{len(entity_ids)} entity/entities"),
        ("pipes_registered", len(pipe_ids) > 0, f"{len(pipe_ids)} pipe/pipes"),
    ]

    for pipe_id in pipe_ids:
        pipe = pipe_registry.get_pipe_definition(pipe_id)
        missing = [entity_id for entity_id in pipe.input_entity_ids if entity_id not in entity_ids]
        checks.append(
            (
                f"pipe.{pipe_id}.input_entities",
                len(missing) == 0,
                "OK" if not missing else f"missing: {', '.join(missing)}",
            )
        )

    for pipe_id in pipe_ids:
        pipe = pipe_registry.get_pipe_definition(pipe_id)
        entity_id = pipe.output_entity_id
        checks.append(
            (
                f"pipe.{pipe_id}.output_entity",
                entity_id in entity_ids,
                "OK" if entity_id in entity_ids else f"missing: {entity_id}",
            )
        )

    for entity_id in sorted(entity_ids):
        entity = entity_registry.get_entity_definition(entity_id)
        is_delta = entity.tags.get("provider_type", "delta") == "delta"
        if is_delta:
            has_merge_columns = bool(entity.merge_columns)
            checks.append(
                (
                    f"entity.{entity_id}.merge_columns",
                    has_merge_columns,
                    "OK" if has_merge_columns else "delta entity missing merge_columns",
                )
            )

    return checks, len(entity_ids), len(pipe_ids)


def _warn_missing_entity_fixtures(entity_registry: Any, pipe_registry: Any) -> None:
    """Print [WARN] lines for delta source entities lacking a local fixture CSV
    (local runs of those pipes will need cloud storage credentials)."""
    entity_ids = set(entity_registry.get_entity_ids())
    cwd = Path.cwd()
    source_entity_ids: set = set()
    for pipe_id in pipe_registry.get_pipe_ids():
        pipe = pipe_registry.get_pipe_definition(pipe_id)
        source_entity_ids.update(pipe.input_entity_ids)
    for entity_id in sorted(source_entity_ids):
        if entity_id not in entity_ids:
            continue
        entity = entity_registry.get_entity_definition(entity_id)
        is_delta = entity.tags.get("provider_type", "delta") == "delta"
        if is_delta and _fixture_csv_path(entity_id, cwd) is None:
            parts = entity_id.replace(".", "/")
            click.echo(
                f"[WARN] entity.{entity_id}.fixture: no fixture CSV at"
                f" tests/entities/{parts}.csv — local runs will require cloud storage"
            )


def _validate_app(env: Optional[str], app_path: Optional[Path]) -> None:
    """Validate entity and pipe definitions without starting Spark."""
    try:
        from kindling.data_entities import DataEntityRegistry
        from kindling.data_pipes import DataPipesRegistry
        from kindling.injection import GlobalInjector
    except ImportError as exc:
        raise click.ClickException(
            "kindling package is required. Install with: pip install spark-kindling[standalone]"
        ) from exc

    resolved_app = _discover_app_py(app_path)
    resolved_env = env or os.getenv("KINDLING_ENV", "local")
    # [implementer] keep validate environment handling symmetric with run — TASK-20260430-002
    _load_app_module(resolved_app, env=resolved_env)

    entity_registry = GlobalInjector.get(DataEntityRegistry)
    pipe_registry = GlobalInjector.get(DataPipesRegistry)
    checks, _entity_count, _pipe_count = _build_entity_pipe_graph_checks(
        entity_registry, pipe_registry
    )

    _print_check_results(checks)
    _warn_missing_entity_fixtures(entity_registry, pipe_registry)

    all_passed = all(passed for _, passed, _ in checks)
    if all_passed:
        click.echo("Validation passed.")
        return

    raise click.ClickException("Validation failed - see above.")


