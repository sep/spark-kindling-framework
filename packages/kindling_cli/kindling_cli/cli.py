def _deep_merge_dict(base: Dict[str, Any], override: Dict[str, Any]) -> Dict[str, Any]:
    """Deep merge dictionaries, with override values winning."""
    merged = dict(base)
    for key, value in override.items():
        if key in merged and isinstance(merged[key], dict) and isinstance(value, dict):
            merged[key] = _deep_merge_dict(merged[key], value)
        else:
            merged[key] = value
    return merged


def _resolve_runtime_parameters(
    parameters_path: Optional[Path], param_overrides: Tuple[str, ...], platform: str = ""
) -> Dict[str, Any]:
    """Load runtime parameters and apply repeatable dotted-key overrides.

    CONFIG__ environment variables (see kindling_sdk.env_config; e.g.
    CONFIG__kindling__temp_path or CONFIG__platform_databricks__kindling__temp_path,
    typically sourced from a shell .env file) form a base layer, so common
    overrides don't need --param on every invocation. The parameters file
    and --param values win over env vars when both set the same key.
    """
    from kindling_sdk.env_config import get_env_config_overrides

    parameters = get_env_config_overrides(os.environ, platform)
    file_parameters = _load_mapping_file(parameters_path, "parameters") if parameters_path else {}
    parameters = _deep_merge_dict(parameters, file_parameters)
    for raw_param in param_overrides:
        if "=" not in raw_param:
            raise click.ClickException("--param values must use KEY=VALUE syntax.")
        key, value = raw_param.split("=", 1)
        key = key.strip()
        if not key:
            raise click.ClickException("--param keys must not be empty.")
        _set_nested_key(parameters, key, _coerce_value(value))
    return parameters


def _run_remote_app(
    app_ref: str,
    app_name: Optional[str],
    env: Optional[str],
    parameters_path: Optional[Path],
    param_overrides: Tuple[str, ...],
    platform: Optional[str],
    no_logs: bool,
    no_wait: bool,
    poll_interval: float,
    timeout: float,
    fail_on_error: bool,
    json_output: bool,
) -> None:
    """Submit a run of an already-deployed app on a remote platform."""
    if poll_interval <= 0:
        raise click.ClickException("--poll-interval must be greater than 0.")
    if timeout <= 0:
        raise click.ClickException("--timeout must be greater than 0.")

    resolved_platform = _resolve_remote_platform(platform)
    resolved_name = (app_name or app_ref).strip()
    if not resolved_name:
        raise click.ClickException("App name resolved to an empty string.")

    api_client, resolved_platform = _create_platform_api(resolved_platform)
    parameters = _resolve_runtime_parameters(parameters_path, param_overrides, resolved_platform)

    try:
        _warn_if_runtime_outdated(_open_store(_resolve_destination()))
    except Exception:
        pass

    _emit_progress(f"Submitting app run `{resolved_name}` on {resolved_platform}...", json_output)
    try:
        run_id = api_client.submit_app_run(
            resolved_name,
            environment=env or None,
            parameters=parameters or None,
        )
    except NotImplementedError:
        raise click.ClickException(
            f"Direct app submission is not yet supported on {resolved_platform}. "
            "Upgrade spark-kindling-sdk when platform support is available."
        )
    _emit_progress(f"Run ID: {run_id}", json_output)

    payload: Dict[str, Any] = {
        "app_name": resolved_name,
        "run_id": run_id,
        "platform": resolved_platform,
    }

    if no_wait:
        _emit_result(
            payload,
            json_output,
            f"Started `{resolved_name}` (run: {run_id}). "
            f"Use `kindling app logs {run_id}` to follow.",
        )
        return

    if not no_logs:
        try:
            api_client.stream_app_run_logs(
                run_id=run_id,
                callback=(lambda line: click.echo(line, err=True)) if json_output else click.echo,
                poll_interval=poll_interval,
                max_wait=timeout,
            )
        except NotImplementedError:
            pass
        except Exception as exc:
            click.echo(f"Log streaming ended early: {exc}", err=True)

    status = _wait_for_app_run(api_client, run_id, poll_interval, timeout)
    state = _status_value(status)
    payload["status"] = status
    payload["state"] = state
    payload["succeeded"] = state in _SUCCESS_JOB_STATES

    if fail_on_error and state not in _SUCCESS_JOB_STATES:
        if json_output:
            _emit_json(payload)
            raise click.exceptions.Exit(1)
        raise click.ClickException(f"Run `{run_id}` finished with state {state}.")

    _emit_result(payload, json_output, f"Run `{run_id}` completed with state {state}.")


