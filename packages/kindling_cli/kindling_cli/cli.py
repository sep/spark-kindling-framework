_KINDLING_DISTRIBUTION_PREFIX = "spark-kindling"


def _canonical_distribution_name(name: str) -> str:
    """Normalize a distribution name the way PyPI does (PEP 503): lowercase,
    with runs of '-', '_', '.' collapsed to a single '-'."""
    return re.sub(r"[-_.]+", "-", name).lower()


def _is_kindling_distribution(name: str) -> bool:
    normalized = _canonical_distribution_name(name)
    return normalized == _KINDLING_DISTRIBUTION_PREFIX or normalized.startswith(
        f"{_KINDLING_DISTRIBUTION_PREFIX}-"
    )


def _load_pyproject_toml(pyproject_path: Path) -> Dict[str, Any]:
    try:
        import tomllib
    except ImportError:
        import tomli as tomllib  # type: ignore[no-redef]
    return tomllib.loads(pyproject_path.read_text(encoding="utf-8"))


def _dependency_extras(entry: Any) -> List[str]:
    if isinstance(entry, dict):
        extras = entry.get("extras", [])
        if isinstance(extras, list):
            return [str(extra) for extra in extras]
    return []


_PEP508_NAME_EXTRAS_RE = re.compile(
    r"^\s*([A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)\s*(\[[^\]]*\])?"
)


def _parse_pep508_name_extras(requirement: str) -> Tuple[str, List[str]]:
    """Best-effort (name, extras) from a PEP 508 requirement string (e.g.
    'spark-kindling[standalone]>=1.0'). Ignores any version specifier/marker
    -- callers only need the name (to match spark-kindling*) and the extras
    uv stores inline in the requirement string rather than in a separate
    table."""
    match = _PEP508_NAME_EXTRAS_RE.match(requirement)
    if not match:
        return requirement.strip(), []
    name = match.group(1)
    extras_str = match.group(2)
    if not extras_str:
        return name, []
    extras = [e.strip() for e in extras_str[1:-1].split(",") if e.strip()]
    return name, extras


def _uv_source_for(sources: Dict[str, Any], name: str) -> Any:
    canonical = _canonical_distribution_name(name)
    for key, value in sources.items():
        if _canonical_distribution_name(key) == canonical:
            return value
    return None


def _uv_synthetic_entry(sources: Dict[str, Any], name: str, extras: List[str]) -> Dict[str, Any]:
    """Build a Poetry-shaped entry dict ({"url": ..., "extras": [...]}) from
    a uv dependency's [tool.uv.sources] override, so _dependency_extras and
    _declared_kindling_version (written against Poetry's dict shape) work
    unchanged against a uv project too."""
    entry: Dict[str, Any] = {}
    source = _uv_source_for(sources, name)
    if isinstance(source, dict) and isinstance(source.get("url"), str):
        entry["url"] = source["url"]
    if extras:
        entry["extras"] = extras
    return entry


def _iter_uv_kindling_dependency_entries(
    data: Dict[str, Any],
) -> Iterator[Tuple[str, Optional[str], Any]]:
    project = data.get("project", {})
    sources = data.get("tool", {}).get("uv", {}).get("sources", {})
    if not isinstance(sources, dict):
        sources = {}

    main_deps = project.get("dependencies", [])
    if isinstance(main_deps, list):
        for requirement in main_deps:
            if not isinstance(requirement, str):
                continue
            name, extras = _parse_pep508_name_extras(requirement)
            if _is_kindling_distribution(name):
                yield name, None, _uv_synthetic_entry(sources, name, extras)

    groups = data.get("dependency-groups", {})
    if isinstance(groups, dict):
        for group_name, group_reqs in groups.items():
            if not isinstance(group_reqs, list):
                continue
            for requirement in group_reqs:
                if not isinstance(requirement, str):
                    continue  # skip {include-group = "..."} entries
                name, extras = _parse_pep508_name_extras(requirement)
                if _is_kindling_distribution(name):
                    yield name, group_name, _uv_synthetic_entry(sources, name, extras)


def _iter_kindling_dependency_entries(
    pyproject_path: Path,
) -> Iterator[Tuple[str, Optional[str], Any]]:
    """Yield (distribution_name, group_or_None, raw_entry) for every declared
    'spark-kindling'/'spark-kindling-*' dependency in pyproject.toml,
    wherever it's declared -- [project.dependencies] or any
    [dependency-groups] group.
    """
    data = _load_pyproject_toml(pyproject_path)
    yield from _iter_uv_kindling_dependency_entries(data)


def _find_kindling_dependencies(
    pyproject_path: Path,
) -> Dict[str, Tuple[Optional[str], List[str]]]:
    """Find every declared Kindling dependency (the framework, SDK, CLI, or
    an extension added via `kindling env add`).

    Returns {distribution_name: (group_or_None, extras)}.
    """
    return {
        name: (group, _dependency_extras(entry))
        for name, group, entry in _iter_kindling_dependency_entries(pyproject_path)
    }


_RELEASE_WHEEL_URL_VERSION_RE = re.compile(r"/releases/download/v([^/]+)/")


def _declared_kindling_version(entry: Any) -> Optional[str]:
    """Best-effort extraction of the pinned version from a declared Kindling
    dependency entry, whether it's a release wheel URL (current convention)
    or a legacy version constraint string/table."""
    if isinstance(entry, dict):
        url = entry.get("url")
        if isinstance(url, str):
            match = _RELEASE_WHEEL_URL_VERSION_RE.search(url)
            if match:
                return match.group(1)
        version = entry.get("version")
        if isinstance(version, str):
            return version
        return None
    if isinstance(entry, str):
        return entry
    return None


_DESCENDANT_SCAN_EXCLUDES = {
    ".git",
    ".venv",
    "venv",
    "node_modules",
    "__pycache__",
    ".tox",
    ".mypy_cache",
    ".pytest_cache",
    "dist",
    "build",
    ".worktrees",
    "site-packages",
}


def _discover_descendant_pyprojects(root_path: Path) -> List[Path]:
    """Find pyproject.toml files in project/app directories nested under
    root_path (e.g. apps/*/pyproject.toml in a monorepo). Does not descend
    past a found pyproject.toml -- nested projects aren't expected to nest
    further -- nor into common non-project directories.
    """
    found: List[Path] = []
    for dirpath, dirnames, filenames in os.walk(root_path):
        dirnames[:] = [
            d for d in dirnames if d not in _DESCENDANT_SCAN_EXCLUDES and not d.startswith(".")
        ]
        current = Path(dirpath)
        if current == root_path:
            continue
        if "pyproject.toml" in filenames:
            found.append(current / "pyproject.toml")
            dirnames[:] = []
    return sorted(found)


def _reconcile_root_kindling_dependencies(
    root_pyproject_path: Path, project_path: Path
) -> Dict[str, Tuple[Optional[str], List[str], Any]]:
    """When root_pyproject_path declares no spark-kindling* dependency, look
    for one declared in a nested package/app under project_path (e.g. a
    monorepo's apps/*/pyproject.toml) so the root can adopt it as the single
    version installed and available to the whole tree.

    Every nested project that declares Kindling must pin the same release --
    the root is a single install, not a per-app one -- so this raises if they
    disagree rather than silently preferring one.

    Returns {distribution: (group, extras, raw_entry)} to add at the root,
    or {} if no nested project declares Kindling either.
    """
    by_project: Dict[Path, Dict[str, Tuple[Optional[str], List[str], Any]]] = {}
    for path in _discover_descendant_pyprojects(project_path):
        try:
            entries = {
                name: (group, _dependency_extras(entry), entry)
                for name, group, entry in _iter_kindling_dependency_entries(path)
            }
        except Exception:
            continue
        if entries:
            by_project[path] = entries

    if not by_project:
        return {}

    versions_by_project: Dict[Path, str] = {}
    for path, entries in by_project.items():
        versions = {
            v for v in (_declared_kindling_version(entry) for _, _, entry in entries.values()) if v
        }
        if len(versions) == 1:
            versions_by_project[path] = next(iter(versions))

    distinct_versions = set(versions_by_project.values())
    if len(distinct_versions) > 1:
        lines = "\n".join(
            f"  {path}: {version}" for path, version in sorted(versions_by_project.items())
        )
        raise click.ClickException(
            f"No spark-kindling* dependency declared at {root_pyproject_path}, and "
            "nested projects disagree on which Kindling release to use:\n"
            f"{lines}\n"
            "Reconcile them to a single release (e.g. `kindling env update` in each) "
            "before running this at the root."
        )

    merged: Dict[str, Tuple[Optional[str], List[str], Any]] = {}
    for entries in by_project.values():
        for name, (group, extras, entry) in entries.items():
            merged.setdefault(name, (group, extras, entry))
    return merged


def _resolve_kindling_release_wheels(
    version: str, repo: str = KINDLING_GITHUB_REPO
) -> Tuple[str, List[Dict[str, str]]]:
    """Resolve a Kindling release and list its wheel assets, without
    downloading any wheel bytes -- `uv add <url>` fetches each wheel
    directly once it's actually added to a project.

    Returns (resolved_version, [{"distribution", "version", "name", "url"}, ...]).
    """
    resolved_version = _resolve_github_version(version, repo=repo)
    tag = f"v{resolved_version}" if not resolved_version.startswith("v") else resolved_version
    release = _github_release_for_tag(tag, repo=repo)
    assets = release.get("assets", [])
    if not isinstance(assets, list):
        raise click.ClickException(f"GitHub release {tag} in {repo} returned malformed assets.")

    wheels: List[Dict[str, str]] = []
    for asset in assets:
        if not (
            isinstance(asset, dict)
            and isinstance(asset.get("name"), str)
            and asset["name"].endswith(".whl")
        ):
            continue
        download_url = asset.get("browser_download_url")
        if not isinstance(download_url, str) or not download_url:
            raise click.ClickException(
                f"Release asset {asset['name']} in {tag} does not include a download URL."
            )
        parts = asset["name"][: -len(".whl")].split("-")
        if len(parts) < 2:
            continue
        wheels.append(
            {
                "distribution": _canonical_distribution_name(parts[0]),
                "version": parts[1],
                "name": asset["name"],
                "url": download_url,
            }
        )

    if not wheels:
        raise click.ClickException(f"No wheel assets found in GitHub release {tag} in {repo}.")
    return resolved_version, wheels


def _remove_stray_bare_uv_dependency(project_path: Path, distribution: str) -> None:
    """`uv add <url> --group G` on an already bare-declared dependency
    doesn't move it into the group -- verified empirically -- it leaves a
    duplicate: the package ends up listed in both [project.dependencies]
    and [dependency-groups.G] at once. Strip the stray bare entry so the
    package is declared in the group only, matching intent.
    """
    pyproject_path = project_path / "pyproject.toml"
    try:
        data = _load_pyproject_toml(pyproject_path)
    except Exception:
        return
    main_deps = data.get("project", {}).get("dependencies", [])
    if not isinstance(main_deps, list):
        return
    canonical = _canonical_distribution_name(distribution)
    is_stray = any(
        isinstance(requirement, str)
        and _canonical_distribution_name(_parse_pep508_name_extras(requirement)[0]) == canonical
        for requirement in main_deps
    )
    if is_stray:
        _run_checked(["uv", "remove", distribution], cwd=project_path)


def _uv_add_url(
    project_path: Path,
    distribution: str,
    url: str,
    *,
    group: Optional[str] = None,
    extras: Optional[List[str]] = None,
) -> None:
    """Run `uv add <url>`, re-supplying group/extras explicitly.

    uv does not infer either from a package's prior pyproject.toml entry: a
    bare `uv add <url>` on an already-declared dependency leaves a stray
    duplicate in [project.dependencies] instead of moving it into its
    group (verified empirically) -- see `_remove_stray_bare_uv_dependency`.
    """
    command = ["uv", "add", url]
    if group:
        command.extend(["--group", group])
    for extra in extras or []:
        command.extend(["--extra", extra])
    _run_checked(command, cwd=project_path)
    if group:
        _remove_stray_bare_uv_dependency(project_path, distribution)


def _sync_command(*, no_sync: bool) -> List[str]:
    """Command to install/sync a project's declared dependencies. `uv sync`
    is already "exact" (removes anything not declared) by default, and
    already includes the default ("dev") dependency group with no extra
    flags needed -- `--inexact` opts out of the removal-of-extraneous-
    packages behavior.
    """
    command = ["uv", "sync"]
    if no_sync:
        command.append("--inexact")
    return command


def _print_kindling_version_report(pyproject_path: Path) -> None:
    """Print each declared Kindling package's pinned version, and whether a
    newer release is available. Purely informational -- being behind the
    latest release doesn't fail the environment check, since it's a valid
    state, not a broken one.
    """
    try:
        entries = list(_iter_kindling_dependency_entries(pyproject_path))
    except Exception as exc:  # malformed pyproject.toml -- degrade, don't fail the check
        click.echo(f"\n(could not read Kindling dependencies from {pyproject_path}: {exc})")
        return
    if not entries:
        return

    resolved_latest: Optional[str] = None
    latest_error: Optional[str] = None
    try:
        resolved_latest, _ = _resolve_kindling_release_wheels("latest")
    except Exception as exc:  # network optional -- degrade, don't fail the check
        latest_error = str(exc)

    click.echo("\nKindling packages:")
    for distribution, group, entry in sorted(entries, key=lambda item: item[0]):
        declared_version = _declared_kindling_version(entry)
        location = f" [{group}]" if group else ""
        if declared_version is None:
            status = "unknown (unrecognized dependency format)"
        elif resolved_latest is None:
            status = declared_version
        elif declared_version == resolved_latest:
            status = f"{declared_version} (up to date)"
        else:
            status = f"{declared_version} (latest: {resolved_latest} -- run `kindling env update`)"
        click.echo(f"  {distribution}{location}: {status}")

    if latest_error:
        click.echo(f"  (could not check latest release: {latest_error})")


@env_group.command("check")
@click.option(
    "--config",
    "config_path",
    default=None,
    show_default=False,
    type=click.Path(path_type=Path, dir_okay=False, exists=False),
)
@click.option(
    "--local",
    "local_checks",
    is_flag=True,
    default=False,
    help=(
        "Also check local Spark dev prerequisites: "
        "Java, PySpark, delta-spark, and hadoop-azure JARs."
    ),
)
@click.option(
    "--platform",
    "platform",
    type=click.Choice(SUPPORTED_PLATFORMS),
    default=None,
    help=(
        "Check pre-flight credential env vars for the given platform "
        "(synapse, databricks, or fabric). Auto-detected from environment if not set."
    ),
)
def env_check(config_path: Optional[Path], local_checks: bool, platform: Optional[str]) -> None:
    """Check if local environment is ready for Kindling.

    \b
    With --local, also validates the Spark runtime stack needed for local
    development and integration tests against ABFSS:

      - Java >=11 on PATH (required by PySpark)
      - pyspark installed
      - delta-spark installed
      - hadoop-azure JARs present in /tmp/hadoop-jars/

    \b
    With --platform <name>, checks that the required env vars for the given
    platform are set and that at least one authentication alternative is
    satisfied.  Vars are reported as SET or MISSING with an export hint;
    auth alternatives are listed in the SDK's credential resolution order.
    Exits 1 unless the platform is ready.

      --platform databricks  DATABRICKS_HOST, plus one of: DATABRICKS_TOKEN,
                             the AZURE_TENANT_ID/AZURE_CLIENT_ID/
                             AZURE_CLIENT_SECRET service principal triple,
                             or a usable Azure CLI session (az login)
      --platform fabric      FABRIC_WORKSPACE_ID and FABRIC_LAKEHOUSE_ID, plus
                             the service principal triple or az login /
                             managed identity
      --platform synapse     SYNAPSE_WORKSPACE_NAME, SYNAPSE_SPARK_POOL_NAME,
                             plus the service principal triple or az login /
                             managed identity

    \b
    To download all required JARs run:
      kindling env ensure

    \b
    If pyproject.toml declares any Kindling dependency, also reports each
    one's pinned version and whether a newer release is available (network
    permitting; this never fails the check). Run `kindling env update` to
    upgrade.
    """
    if config_path is None:
        config_path = Path("settings.yaml")
    resolved_config_path = config_path.expanduser()

    checks: List[Tuple[str, bool, str]] = []
    checks.append(
        (
            "python_version",
            sys.version_info >= (3, 10),
            f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro} (>=3.10)",
        )
    )

    exists = resolved_config_path.exists()
    checks.append(("config_file_exists", exists, str(resolved_config_path)))

    config_data: Dict[str, Any] = {}
    if exists:
        config_data = _load_yaml_config(resolved_config_path)

    kindling_section = config_data.get("kindling")
    has_kindling_section = isinstance(kindling_section, dict)
    checks.append(("kindling_section_present", has_kindling_section, "root.kindling is a mapping"))

    if local_checks:
        java_ok, java_detail = _check_java()
        checks.append(("java", java_ok, java_detail))

        pyspark_ok, pyspark_detail = _check_module("pyspark")
        checks.append(("pyspark", pyspark_ok, pyspark_detail))

        delta_ok, delta_detail = _check_module("delta")
        checks.append(("delta_spark", delta_ok, delta_detail))

        jars_ok, jars_detail = _check_hadoop_jars()
        checks.append(("hadoop_azure_jars", jars_ok, jars_detail))
        if not jars_ok:
            missing = [j for j in _HADOOP_AZURE_JARS if not (_HADOOP_JAR_DIR / j).exists()]
            checks.append(
                (
                    "  missing_jars",
                    False,
                    ", ".join(missing),
                )
            )

    # [implementer] human-readable platform credential check — ki-0nq
    if platform is not None:
        all_set = _print_platform_credential_check(platform)
        sys.exit(0 if all_set else 1)

    auto_platform = _detect_platform_from_environment()
    if auto_platform:
        checks.append(("platform", True, auto_platform))
        for var in _PLATFORM_BASE_VARS.get(auto_platform, []):
            val = os.getenv(var)
            checks.append((f"env:{var}", bool(val), "set" if val else "missing"))
        if auto_platform == "databricks":
            satisfied_by, _ = _evaluate_platform_auth(auto_platform)
            checks.append(
                (
                    "databricks_auth",
                    satisfied_by is not None,
                    satisfied_by
                    or "missing — set DATABRICKS_TOKEN, the AZURE_* service principal"
                    " vars, or run az login",
                )
            )
        elif auto_platform in _AZURE_SP_PLATFORMS:
            sp_vals = [os.getenv(v) for v in _AZURE_SP_VARS]
            if any(sp_vals):
                for var, val in zip(_AZURE_SP_VARS, sp_vals):
                    checks.append((f"env:{var}", bool(val), "set" if val else "missing"))
            else:
                checks.append(("azure_auth", True, "az login / managed identity"))

    passed = _print_check_results(checks)

    project_pyproject = Path("pyproject.toml")
    if project_pyproject.exists():
        _print_kindling_version_report(project_pyproject)

    if passed:
        click.echo("Environment check passed.")
        return

    raise click.ClickException("Environment check failed.")


_CLOUD_AZURE = "azure"
_SUPPORTED_CLOUDS = [_CLOUD_AZURE]


def _detect_cloud() -> Optional[str]:
    """Return the detected cloud provider based on available CLI tools, or None."""
    if shutil.which("az"):
        return _CLOUD_AZURE
    return None


def _azure_jar_specs() -> List[Tuple[str, str, Optional[str]]]:
    return [(url.split("/")[-1], url, None) for url in _HADOOP_JAR_URLS] + [
        (_ABFSS_LOCAL_AUTH_JAR, _ABFSS_LOCAL_AUTH_JAR_URL, _ABFSS_LOCAL_AUTH_JAR_SHA256)
    ]


@env_group.command("ensure")
@click.option(
    "--cloud",
    type=click.Choice(_SUPPORTED_CLOUDS, case_sensitive=False),
    default=None,
    help=(
        "Cloud provider to download JARs for. "
        "If omitted, auto-detected from available CLI tools (az → azure)."
    ),
)
def env_ensure(cloud: Optional[str]) -> None:
    """Download JARs required for local standalone cloud storage development.

    \b
    Without --cloud, the cloud provider is inferred from available CLI tools:
      az  → azure  (downloads hadoop-azure JARs + kindling-abfss-local-auth.jar)

    Downloads into /tmp/hadoop-jars/. Safe to re-run — existing JARs are skipped.
    """
    import hashlib
    import urllib.request

    resolved_cloud = cloud or _detect_cloud()

    if resolved_cloud is None:
        click.echo(
            "No cloud provider detected.\n"
            "Install a cloud CLI (e.g. 'az' for Azure) or pass --cloud explicitly.\n"
            f"Supported clouds: {', '.join(_SUPPORTED_CLOUDS)}"
        )
        return

    if cloud is None:
        click.echo(f"Detected cloud: {resolved_cloud}")

    if resolved_cloud == _CLOUD_AZURE:
        jar_specs = _azure_jar_specs()
    else:
        raise click.ClickException(f"No JAR spec defined for cloud '{resolved_cloud}'.")

    _HADOOP_JAR_DIR.mkdir(parents=True, exist_ok=True)

    all_ok = True
    for jar_name, url, expected_sha256 in jar_specs:
        dest = _HADOOP_JAR_DIR / jar_name
        if dest.exists():
            click.echo(f"  ok       {jar_name}")
            continue
        click.echo(f"  download {jar_name} ...", nl=False)
        try:
            urllib.request.urlretrieve(url, dest)  # nosec B310
            if expected_sha256:
                actual = hashlib.sha256(dest.read_bytes()).hexdigest()
                if actual != expected_sha256:
                    dest.unlink(missing_ok=True)
                    click.echo(" CHECKSUM MISMATCH — removed")
                    all_ok = False
                    continue
            click.echo(" done")
        except Exception as exc:
            dest.unlink(missing_ok=True)
            click.echo(f" FAILED: {exc}")
            all_ok = False

    if all_ok:
        click.echo(f"\nAll JARs present in {_HADOOP_JAR_DIR}")
    else:
        raise click.ClickException("One or more JARs could not be downloaded.")


@env_group.command("update")
@click.option(
    "--version",
    default="latest",
    show_default=True,
    help="Kindling release version or tag to update to.",
)
@click.option(
    "--repo",
    default=KINDLING_GITHUB_REPO,
    show_default=True,
    help="GitHub repository containing Kindling release wheel assets.",
)
@click.option(
    "--project",
    "project_path",
    type=click.Path(path_type=Path, file_okay=False),
    default=Path("."),
    show_default=True,
    help="uv project to update.",
)
@click.option(
    "--no-sync",
    is_flag=True,
    help="Run uv sync with --inexact (don't remove extraneous packages).",
)
def env_update(version: str, repo: str, project_path: Path, no_sync: bool) -> None:
    """Update every Kindling package this project already depends on.

    Finds every dependency named 'spark-kindling' or 'spark-kindling-*'
    (the framework, SDK, CLI, and any extensions added via
    `kindling env add`) declared anywhere in pyproject.toml, and points
    each one at its matching wheel in the target Kindling release
    (default: latest) via `uv add <release wheel url>`. Every
    Kindling package in a release is versioned together, so one release
    resolves every dependency at once -- no local wheel cache or Poetry
    source configuration required.

    If nothing is declared at PROJECT itself, looks for a Kindling
    dependency in a nested package/app pyproject.toml (e.g. a monorepo's
    apps/*/pyproject.toml) and adopts it before updating -- the project
    root is the single source of truth for what's installed. Fails if
    nested projects disagree on which release to use.
    """
    project_path = project_path.expanduser().resolve()
    pyproject_path = project_path / "pyproject.toml"
    if not pyproject_path.exists():
        raise click.ClickException(f"No pyproject.toml found at {project_path}.")

    declared = _find_kindling_dependencies(pyproject_path)
    if not declared:
        to_copy = _reconcile_root_kindling_dependencies(pyproject_path, project_path)
        if not to_copy:
            raise click.ClickException(
                f"No spark-kindling* dependencies found in {pyproject_path}."
            )
        click.echo(
            f"No spark-kindling* dependency declared at {pyproject_path}; "
            "adopting from nested project(s):"
        )
        for distribution in sorted(to_copy):
            group, extras, _entry = to_copy[distribution]
            location = f" [{group}]" if group else ""
            click.echo(f"  {distribution}{location}")
        declared = {name: (group, extras) for name, (group, extras, _entry) in to_copy.items()}

    resolved_version, wheels = _resolve_kindling_release_wheels(version, repo=repo)
    wheels_by_distribution = {wheel["distribution"]: wheel for wheel in wheels}

    click.echo(f"Updating Kindling packages in {pyproject_path} to {resolved_version} ({repo})")
    updated = False
    for distribution, (group, extras) in sorted(declared.items()):
        match = wheels_by_distribution.get(_canonical_distribution_name(distribution))
        if match is None:
            click.echo(f"  skipped {distribution}: not published in Kindling {resolved_version}")
            continue
        _uv_add_url(project_path, distribution, match["url"], group=group, extras=extras)
        location = f" [{group}]" if group else ""
        click.echo(f"  {distribution} -> {match['version']}{location}")
        updated = True

    if not updated:
        raise click.ClickException(
            f"None of the declared Kindling dependencies were found in release {resolved_version}."
        )

    _run_checked(_sync_command(no_sync=no_sync), cwd=project_path)

    click.echo(f"\nKindling packages in {project_path} are up to date at {resolved_version}.")


@env_group.command("add")
@click.argument("package")
@click.option(
    "--version",
    default="latest",
    show_default=True,
    help="Kindling release version or tag to resolve PACKAGE's version from.",
)
@click.option(
    "--repo",
    default=KINDLING_GITHUB_REPO,
    show_default=True,
    help="GitHub repository containing Kindling release wheel assets.",
)
@click.option(
    "--project",
    "project_path",
    type=click.Path(path_type=Path, file_okay=False),
    default=Path("."),
    show_default=True,
    help="uv project to add the dependency to.",
)
@click.option(
    "--group",
    "dependency_group",
    default=None,
    help="Dependency group for PACKAGE if it isn't already declared "
    "(e.g. 'dev'). Ignored if PACKAGE already exists in a group.",
)
def env_add(
    package: str,
    version: str,
    repo: str,
    project_path: Path,
    dependency_group: Optional[str],
) -> None:
    """Add a Kindling framework or extension package as a project dependency.

    Resolves PACKAGE's wheel from the given Kindling release (default:
    latest) and runs `uv add <release wheel url>`, pinning PACKAGE to
    the exact wheel published for that release -- no local wheel cache or
    Poetry-style source configuration required.

    \b
    Examples:
        kindling env add spark-kindling-ext-databricks
        kindling env add spark-kindling-ext-sdp --group dev
    """
    project_path = project_path.expanduser().resolve()
    pyproject_path = project_path / "pyproject.toml"
    if not pyproject_path.exists():
        raise click.ClickException(f"No pyproject.toml found at {project_path}.")

    normalized_target = _canonical_distribution_name(package)
    resolved_version, wheels = _resolve_kindling_release_wheels(version, repo=repo)
    match = next((wheel for wheel in wheels if wheel["distribution"] == normalized_target), None)
    if match is None:
        available = sorted({wheel["distribution"] for wheel in wheels})
        raise click.ClickException(
            f"'{package}' is not among the wheel assets in Kindling {resolved_version} "
            f"({repo}). Available: {', '.join(available)}"
        )

    declared = _find_kindling_dependencies(pyproject_path)
    existing = next(
        (
            v
            for name, v in declared.items()
            if _canonical_distribution_name(name) == normalized_target
        ),
        None,
    )
    if existing is not None:
        existing_group, existing_extras = existing
        if dependency_group and dependency_group != existing_group:
            location = (
                "main dependencies" if existing_group is None else f"'{existing_group}' group"
            )
            click.echo(
                f"'{package}' is already declared in the {location}; ignoring --group {dependency_group}."
            )
        group, extras = existing_group, existing_extras
    else:
        group, extras = dependency_group, []

    click.echo(f"Resolving {package} {match['version']} from Kindling {resolved_version} ({repo})")
    _uv_add_url(project_path, normalized_target, match["url"], group=group, extras=extras)

    location = f" [{group}]" if group else ""
    click.echo(f"\nAdded {package} {match['version']}{location} to {pyproject_path}.")


_BOOTSTRAP_PACKAGES: Tuple[Tuple[str, Optional[str], List[str]], ...] = (
    ("spark-kindling", None, ["standalone"]),
    ("spark-kindling-sdk", "dev", []),
    ("spark-kindling-cli", "dev", []),
)


@env_group.command("bootstrap")
@click.option(
    "--version",
    default="latest",
    show_default=True,
    help="Kindling release version or tag to install if no Kindling dependency is declared yet.",
)
@click.option(
    "--repo",
    default=KINDLING_GITHUB_REPO,
    show_default=True,
    help="GitHub repository containing Kindling release wheel assets.",
)
@click.option(
    "--project",
    "project_path",
    type=click.Path(path_type=Path, file_okay=False),
    default=Path("."),
    show_default=True,
    help="uv project to bootstrap.",
)
@click.option(
    "--no-sync",
    is_flag=True,
    help="Run uv sync with --inexact (don't remove extraneous packages).",
)
def env_bootstrap(version: str, repo: str, project_path: Path, no_sync: bool) -> None:
    """Ensure a project can load Kindling, adding it if it isn't declared yet.

    Checks pyproject.toml for any 'spark-kindling'/'spark-kindling-*'
    dependency. If none is declared -- a project created without
    `kindling repo init`, or one that predates this devcontainer's package
    model -- looks for one declared in a nested package/app pyproject.toml
    (e.g. a monorepo's apps/*/pyproject.toml) and adopts it; only if no
    nested project declares Kindling either does it add the framework, SDK,
    and CLI pinned to the target Kindling release (default: latest) via
    `uv add <release wheel URL>`. Fails if nested projects disagree on
    which release to use. If Kindling is already declared at the project
    root, this leaves it untouched: the project's own pyproject.toml/
    uv.lock remain authoritative. Either way, finishes with `uv sync`.

    This is what the generated devcontainer's `postCreateCommand` runs on
    every container creation, so a domain project always ends up with a
    working Kindling install without the devcontainer image itself
    installing Kindling packages directly.
    """
    project_path = project_path.expanduser().resolve()
    pyproject_path = project_path / "pyproject.toml"
    if not pyproject_path.exists():
        raise click.ClickException(f"No pyproject.toml found at {project_path}.")

    if _find_kindling_dependencies(pyproject_path):
        click.echo(f"Kindling is already declared in {pyproject_path}.")
    else:
        to_copy = _reconcile_root_kindling_dependencies(pyproject_path, project_path)
        if to_copy:
            click.echo(
                f"No Kindling dependency found in {pyproject_path}; "
                "copying from nested project(s):"
            )
            for distribution, (group, extras, entry) in sorted(to_copy.items()):
                url = entry.get("url") if isinstance(entry, dict) else None
                if not url:
                    continue
                _uv_add_url(project_path, distribution, url, group=group, extras=extras)
                location = f" [{group}]" if group else ""
                click.echo(f"  added {distribution}{location} (from nested project)")
        else:
            click.echo(f"No Kindling dependency found in {pyproject_path}; adding it.")
            resolved_version, wheels = _resolve_kindling_release_wheels(version, repo=repo)
            wheels_by_distribution = {wheel["distribution"]: wheel for wheel in wheels}

            for distribution, group, extras in _BOOTSTRAP_PACKAGES:
                match = wheels_by_distribution.get(distribution)
                if match is None:
                    raise click.ClickException(
                        f"'{distribution}' is not among the wheel assets in Kindling "
                        f"{resolved_version} ({repo})."
                    )
                _uv_add_url(project_path, distribution, match["url"], group=group, extras=extras)
                location = f" [{group}]" if group else ""
                click.echo(f"  added {distribution} {match['version']}{location}")

    _run_checked(_sync_command(no_sync=no_sync), cwd=project_path)

    click.echo(f"\nKindling is ready in {project_path}.")


