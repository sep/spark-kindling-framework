def _normalize_archive_entry_path(entry_name: str) -> str:
    """Validate and normalize archive entry paths to safe POSIX-relative paths."""
    normalized = str(entry_name or "").replace("\\", "/").strip()
    if not normalized:
        raise click.ClickException("Archive contains an empty file path.")
    if normalized.startswith("/") or (len(normalized) >= 2 and normalized[1] == ":"):
        raise click.ClickException(f"Archive contains an unsafe absolute path: `{entry_name}`")

    posix_path = PurePosixPath(normalized)
    if any(part in ("", ".", "..") for part in posix_path.parts):
        raise click.ClickException(
            f"Archive contains an unsafe relative path traversal: `{entry_name}`"
        )

    return posix_path.as_posix()


def _prepare_app_files(
    app_path: Path,
    *,
    platform: Optional[str] = None,
    environment: Optional[str] = None,
) -> Dict[str, str]:
    """Collect app source files from a directory or a .kda archive."""
    resolved_path = app_path.expanduser().resolve()

    if resolved_path.is_file() and resolved_path.suffix.lower() == ".kda":
        app_files: Dict[str, str] = {}
        try:
            with zipfile.ZipFile(resolved_path, "r") as archive:
                for file_info in archive.infolist():
                    if file_info.is_dir():
                        continue
                    rel_path = _normalize_archive_entry_path(file_info.filename)
                    if not is_deployable_app_file(
                        rel_path,
                        platform=platform,
                        environment=environment,
                    ):
                        continue
                    app_files[rel_path] = archive.read(file_info.filename).decode("utf-8")
        except Exception as exc:
            raise click.ClickException(
                f"Failed to read app package `{resolved_path}`: {exc}"
            ) from exc

        if not app_files:
            raise click.ClickException(
                f"No application files were found in `{resolved_path}`. "
                "Expected .py, .yaml, .yml, requirements.txt, or lake-reqs.txt entries."
            )
        return app_files

    if resolved_path.is_dir():
        app_files = {}
        for file_path in sorted(resolved_path.rglob("*")):
            if not file_path.is_file():
                continue
            rel_path = file_path.relative_to(resolved_path).as_posix()
            if not is_deployable_app_file(
                rel_path,
                platform=platform,
                environment=environment,
            ):
                continue
            app_files[rel_path] = _read_text_file(file_path)

        if not app_files:
            raise click.ClickException(
                f"No application files were found in `{resolved_path}`. "
                "Expected at least one .py, .yaml, .yml, requirements.txt, or lake-reqs.txt file."
            )
        return app_files

    raise click.ClickException(
        f"Invalid app path `{resolved_path}`. Expected a directory or a `.kda` archive."
    )


def _validate_app_entry_point(app_files: Dict[str, str], app_path: Path) -> None:
    """Ensure app.yaml's configured entry point is included in deploy files."""
    config_content = app_files.get(APP_CONFIG_FILE)
    if not config_content:
        return

    try:
        config_data = yaml.safe_load(config_content) or {}
    except Exception as exc:
        raise click.ClickException(
            f"Failed to parse `{APP_CONFIG_FILE}` from `{app_path}`: {exc}"
        ) from exc

    if not isinstance(config_data, dict):
        raise click.ClickException(
            f"`{APP_CONFIG_FILE}` from `{app_path}` must contain a YAML object."
        )

    entry_point = str(config_data.get("entry_point", DEFAULT_APP_ENTRY_POINT)).strip()
    if not entry_point:
        raise click.ClickException(
            f"`{APP_CONFIG_FILE}` from `{app_path}` has an empty entry_point."
        )
    if entry_point in app_files:
        return

    available = ", ".join(sorted(app_files)) or "no deployable files"
    raise click.ClickException(
        f"`{APP_CONFIG_FILE}` from `{app_path}` declares "
        f"entry_point `{entry_point}`, but that file is not included in the app artifact.\n"
        f"  Files included for deploy: {available}\n"
        "  Hint: update app.yaml to the real entry point, deploy from the app directory "
        "that contains it, or add the missing file."
    )


