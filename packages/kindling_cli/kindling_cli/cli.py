def _deploy_config(
    store: ArtifactStore,
    config_path: Path,
    overwrite: bool = True,
    platform: Optional[str] = None,
    environment: Optional[str] = None,
) -> None:
    """Upload settings.yaml and selected dot-style settings overlays to config/."""
    config_dir = config_path.parent
    config_files = [config_path]
    if platform:
        config_files.extend(
            [
                config_dir / f"settings.{platform}.yaml",
                config_dir / f"settings.{platform}.yml",
            ]
        )
    if environment:
        config_files.extend(
            [
                config_dir / f"settings.{environment}.yaml",
                config_dir / f"settings.{environment}.yml",
            ]
        )
    # De-duplicate while preserving order
    seen: set = set()
    unique: List[Path] = []
    for f in config_files:
        resolved = f.resolve()
        if resolved not in seen and resolved.exists():
            seen.add(resolved)
            unique.append(f)

    for f in unique:
        if store.upload_file(f"config/{f.name}", f.read_bytes(), overwrite=overwrite):
            click.echo(f"  {f.name}")
        else:
            click.echo(f"  {f.name} (exists, skipped)")


def _make_jupyter_notebook(cells: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Build a minimal Jupyter notebook document from a list of cell dicts."""
    return {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {"name": "python", "version": "3.10.0"},
        },
        "cells": cells,
    }


